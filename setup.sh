#!/usr/bin/env bash
# Mini-SOC one-button setup.
#
#   ./setup.sh            build (or resume building) the whole lab
#   ./setup.sh status     show which VMs exist and where to log in
#   ./setup.sh stop       shut all VMs down (keeps them)
#   ./setup.sh destroy    delete all VMs (asks first)
#
# Settings (which VMs, how much RAM, versions) live in lab.conf.
set -euo pipefail
cd "$(dirname "$0")"

VAGRANT_VERSION=2.4.9
SECRETS=.lab/secrets.env
ACCESS=.lab/ACCESS.txt

bold() { printf '\033[1m%s\033[0m\n' "$*"; }
info() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m==> WARNING:\033[0m %s\n' "$*"; }
fail() { printf '\033[1;31m==> ERROR:\033[0m %s\n' "$*" >&2; exit 1; }

# lab.conf values (environment variables win)
conf() { local v="${!1:-}"; [ -n "$v" ] && { echo "$v"; return; }
         sed -n "s/^$1=\([^#]*\).*/\1/p" lab.conf | tr -d ' "' | tail -1; }
enabled() { [ "$(conf "ENABLE_$1")" != "false" ]; }

# ------------------------------------------------------------------ checks
check_host() {
    command -v VBoxManage >/dev/null || fail "VirtualBox is not installed. Install it from https://www.virtualbox.org and run ./setup.sh again."
    info "VirtualBox $(VBoxManage --version)"

    if ! command -v vagrant >/dev/null; then
        info "Vagrant not found - installing Vagrant ${VAGRANT_VERSION} into ~/.local/bin (no sudo needed)"
        local tmp; tmp=$(mktemp -d)
        curl -fsSL -o "$tmp/vagrant.zip" "https://releases.hashicorp.com/vagrant/${VAGRANT_VERSION}/vagrant_${VAGRANT_VERSION}_linux_amd64.zip"
        mkdir -p "$HOME/.local/bin"
        unzip -q -o "$tmp/vagrant.zip" -d "$HOME/.local/bin" vagrant
        rm -rf "$tmp"
        export PATH="$HOME/.local/bin:$PATH"
    fi
    info "$(vagrant --version)"

    # RAM: sum up what lab.conf asks for and compare with the host
    local need=$(( $(conf FW_MEMORY) + $(conf WAZUH_MEMORY) ))
    enabled SOC    && need=$(( need + $(conf SOC_MEMORY) ))
    enabled SENSOR && need=$(( need + $(conf SENSOR_MEMORY) ))
    enabled TARGET && need=$(( need + $(conf TARGET_MEMORY) ))
    enabled KALI   && need=$(( need + $(conf KALI_MEMORY) ))
    local have; have=$(( $(awk '/MemTotal/{print $2}' /proc/meminfo) / 1024 ))
    info "Memory: lab needs ${need} MB, this computer has ${have} MB"
    if (( need > have - 3072 )); then
        warn "That is tight - your computer needs ~3 GB for itself. Disable VMs or lower memory in lab.conf."
        read -r -p "Continue anyway? [y/N] " a; [[ "$a" =~ ^[yY]$ ]] || exit 1
    fi

    local free_gb; free_gb=$(df -Pk "$HOME" | awk 'NR==2{print int($4/1024/1024)}')
    (( free_gb >= 60 )) || warn "Only ${free_gb} GB free disk space - the full lab uses about 60 GB."
}

# ------------------------------------------------------------------ secrets
rand() { tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1"; }

make_secrets() {
    [ -f "$SECRETS" ] && { info "Using existing lab passwords ($SECRETS)"; return; }
    info "Generating lab passwords"
    mkdir -p .lab && chmod 700 .lab
    # Wazuh requires upper + lower case, a digit and one of . * + ? -
    umask 077
    cat > "$SECRETS" <<EOF
# Generated by setup.sh on $(date '+%Y-%m-%d %H:%M'). Keep this file private.
LAB_PASSWORD=Soc-$(rand 14).7
IRIS_API_KEY=$(rand 48)
IRIS_DB_PASSWORD=$(rand 24)
IRIS_DB_ADMIN_PASSWORD=$(rand 24)
IRIS_SECRET_KEY=$(rand 48)
IRIS_PASSWORD_SALT=$(rand 32)
EOF
}

# ------------------------------------------------------------------ build
build() {
    local vms=(fw wazuh)
    enabled SOC    && vms+=(soc)
    enabled SENSOR && vms+=(sensor)
    enabled TARGET && vms+=(target)
    enabled KALI   && vms+=(kali)

    bold ""
    bold "Building the Mini-SOC lab: ${vms[*]}"
    bold "First run: 45-90 minutes depending on your internet connection."
    bold "Logs per VM: .lab/<vm>.log   (safe to re-run ./setup.sh if something fails)"
    bold ""

    for vm in "${vms[@]}"; do
        if [ -f ".lab/$vm.done" ]; then
            if [ "$(vagrant status "$vm" --machine-readable | awk -F, '$3=="state"{print $4}')" = "running" ]; then
                info "$vm: already built and running"
            else
                info "$vm: already built - starting it"
                vagrant up "$vm" --no-provision > ".lab/$vm.log" 2>&1 || fail "$vm did not start - see .lab/$vm.log"
            fi
            continue
        fi
        info "$vm: building ..."
        local start=$SECONDS
        if ! vagrant up "$vm" --provision > ".lab/$vm.log" 2>&1; then
            tail -20 ".lab/$vm.log"
            fail "$vm failed after $(( (SECONDS - start) / 60 )) min - full log: .lab/$vm.log. Fix the cause and run ./setup.sh again."
        fi
        touch ".lab/$vm.done"
        info "$vm: done in $(( (SECONDS - start) / 60 )) min"
    done
}

# ------------------------------------------------------------------ summary
summary() {
    # shellcheck disable=SC1090
    local pw; pw=$(sed -n 's/^LAB_PASSWORD=//p' "$SECRETS")
    {
        echo "Mini-SOC lab - access"
        echo "====================="
        echo
        echo "Lab password (all web interfaces): $pw"
        echo
        printf '%-12s %-32s %s\n' "Tool" "URL" "User"
        printf '%-12s %-32s %s\n' "OPNsense"  "https://localhost:$(conf PORT_OPNSENSE)" "root"
        printf '%-12s %-32s %s\n' "Wazuh"     "https://localhost:$(conf PORT_WAZUH)"    "admin"
        if enabled SOC; then
            printf '%-12s %-32s %s\n' "DFIR-IRIS" "https://localhost:$(conf PORT_IRIS)"      "administrator"
            printf '%-12s %-32s %s\n' "Greenbone" "https://localhost:$(conf PORT_GREENBONE)" "admin"
        fi
        if enabled TARGET; then
            printf '%-12s %-32s %s\n' "target" "http://localhost:$(conf PORT_TARGET)/" "practice target - see below"
        fi
        echo
        echo "Browsers will warn about the certificates: the lab uses self-signed"
        echo "certificates, so accept the warning (Advanced > Continue). 'target' is"
        echo "plain http:// and deliberately doesn't look like a training app at"
        echo "first glance - see the README's \"Red team exercise\" section for what"
        echo "to actually do with it."
        echo
        local vms="fw|wazuh"
        enabled SOC && vms+="|soc"; enabled SENSOR && vms+="|sensor"
        enabled TARGET && vms+="|target"; enabled KALI && vms+="|kali"
        echo "Shell access:   vagrant ssh <${vms}>"
    } > "$ACCESS"
    chmod 600 "$ACCESS"
    echo; cat "$ACCESS"; echo
    info "This overview is saved in $ACCESS"
}

case "${1:-up}" in
    up)
        check_host
        make_secrets
        build
        summary ;;
    status)
        vagrant status
        [ -f "$ACCESS" ] && { echo; cat "$ACCESS"; } ;;
    stop)
        vagrant halt ;;
    destroy)
        read -r -p "Delete ALL lab VMs? Lab passwords in .lab/ are kept. [y/N] " a
        [[ "$a" =~ ^[yY]$ ]] || exit 0
        vagrant destroy -f
        rm -f .lab/*.done ;;
    *)
        sed -n '2,9p' "$0"; exit 1 ;;
esac
